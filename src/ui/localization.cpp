std::string Localize(Language language, std::string_view text) {
  return language == Language::SIMPLIFIED_CHINESE ? Translate(text, 0u) : std::string(text);
}

std::string LocalizedLabel(Language language, std::string_view label) {
  const size_t visible_end = label.find("##");
  if (visible_end == 0u) return std::string(label);
  const auto visible = label.substr(0u, visible_end);
  const size_t stable = label.find("###");
  const auto id = stable == std::string_view::npos ? label : label.substr(stable + 3u);
  return Localize(language, visible) + "###" + std::string(id);
}
