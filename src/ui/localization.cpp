struct Pattern {
  std::vector<std::string_view> literals;
  size_t literal_bytes = 0u;
};

Pattern Split(std::string_view text) {
  Pattern result;
  size_t start = 0u;
  const bool braces = text.find('{') != std::string_view::npos;
  for (size_t i = 0u; i < text.size(); ++i) {
    size_t end = std::string_view::npos;
    if (text[i] == '{' && (i + 1u == text.size() || text[i + 1u] != '{')) {
      const size_t close = text.find('}', i + 1u);
      if (close != std::string_view::npos) end = close + 1u;
    } else if (!braces && text[i] == '%' && i + 1u < text.size() && text[i + 1u] != '%') {
      size_t at = i + 1u;
      while (at < text.size() && std::string_view("-+#0123456789.lz").find(text[at]) != std::string_view::npos) ++at;
      if (at < text.size() && std::string_view("sufdixXgGeE").find(text[at]) != std::string_view::npos) end = at + 1u;
    }
    if (end != std::string_view::npos) {
      result.literals.push_back(text.substr(start, i - start));
      result.literal_bytes += i - start;
      start = end;
      i = end - 1u;
    }
  }
  result.literals.push_back(text.substr(start));
  result.literal_bytes += text.size() - start;
  return result;
}

struct FormattedTranslation {
  Pattern english;
  Pattern chinese;
};

const std::vector<FormattedTranslation>& Formats() {
  static const auto formats = [] {
    std::vector<FormattedTranslation> result;
    for (const auto& row : CHINESE) {
      auto source = Split(row.english);
      auto target = Split(row.chinese);
      // Require actual surrounding text; a bare placeholder must never match arbitrary diagnostics or technical identifiers.
      if (source.literals.size() > 1u && source.literals.size() == target.literals.size() && source.literal_bytes >= 4u) {
        result.push_back({std::move(source), std::move(target)});
      }
    }
    std::ranges::stable_sort(result, [](const auto& a, const auto& b) { return a.english.literal_bytes > b.english.literal_bytes; });
    return result;
  }();
  return formats;
}

bool Match(const Pattern& pattern, std::string_view text, std::vector<std::string_view>* arguments) {
  if (!text.starts_with(pattern.literals.front())) return false;
  size_t at = pattern.literals.front().size();
  for (size_t i = 1u; i < pattern.literals.size(); ++i) {
    const auto literal = pattern.literals[i];
    const bool last = i + 1u == pattern.literals.size();
    if (literal.empty() && !last) return false;
    size_t end;
    if (last) {
      if (!text.ends_with(literal) || text.size() - literal.size() < at) return false;
      end = text.size() - literal.size();
    } else {
      end = text.find(literal, at);
      if (end == std::string_view::npos) return false;
    }
    arguments->push_back(text.substr(at, end - at));
    at = end + literal.size();
  }
  return at == text.size();
}

std::string Translate(std::string_view text, unsigned depth) {
  const auto found = std::ranges::lower_bound(CHINESE, text, {}, &Translation::english);
  if (found != CHINESE.end() && found->english == text) return std::string(found->chinese);
  if (depth < 4u) {
    if (text.find('\n') != std::string_view::npos) {
      std::string lines;
      size_t start = 0u;
      while (start <= text.size()) {
        const size_t end = text.find('\n', start);
        lines += Translate(text.substr(start, end == std::string_view::npos ? end : end - start), depth + 1u);
        if (end == std::string_view::npos) break;
        lines += '\n';
        start = end + 1u;
      }
      return lines;
    }
    for (const auto& row : Formats()) {
      std::vector<std::string_view> arguments;
      if (!Match(row.english, text, &arguments)) continue;
      std::string result(row.chinese.literals.front());
      for (size_t i = 0u; i < arguments.size(); ++i) {
        result += Translate(arguments[i], depth + 1u);
        result += row.chinese.literals[i + 1u];
      }
      return result;
    }
  }
  return std::string(text);
}
